--[[
EMCO Chat Package README

Installation
- lua installPackage("https://github.com/dragonsgatereborn/EMCO/releases/latest/download/EMCOChat.mpackage")
- emco update (updates from GitHub)

Usage
- demonnic.chat:append("TabName") to send lines to a tab
- demonnic.chat:cecho("TabName", "message\n") for custom output

Available aliases
- emco addtab <tabname>
- emco blankLine <true|false>
- emco blink <true|false>
- emco color <option> <value>
- emco font <fontname>
- emco fontSize <size>
- emco tabFontSize <size>
- emco addFontSize <size> (alias for tabFontSize)
- emco gag <pattern>
- emco gaglist
- emco hide
- emco load
- emco lock
- emco notify <tabName>
- emco remtab <tabname>
- emco save
- emco show
- emco timestamp <true|false>
- emco title <new title>
- emco unlock
- emco ungag <pattern>
- emco unnotify <tabName>
- emco update
- emco version

Repository
- https://github.com/dragonsgatereborn/EMCO
--]]
